"""Масштаб просмотра → σ клика. План 3, задача 8; открытие 1 плана.

Единственное место, где масштаб показа превращается в погрешность. Qt не импортирует.

Модель:

    σ_кадра = √( (σ_экрана / s)² + σ_кромки² )

`s` — экранных пикселей на пиксель кадра (1.0 — режим 1:1). `σ_экрана` — промах
руки и глаза в ЭКРАННЫХ пикселях, величина о человеке и об экране; `σ_кромки` —
размытость самой кромки в пикселях КАДРА. Источники независимы и складываются
квадратично: ни увеличение не делает клик точнее кромки, ни резкая кромка не
спасает клик по уменьшенному экрану.

Следствие, которое план 3 обязан назвать (открытие 1): при 1:1 σ = 1.92 px, и одно
слагаемое локализации бюджета п. 6.1 при GSD 5 мм/px — 13.6 мм, больше допуска
10 мм п. 2.2. Константа плана 1 `DEFAULT_MARK_SIGMA_PX = 1.0` — предел СИЛЬНОГО
увеличения, а не режима 1:1. Поэтому интерфейс ведёт оператора к увеличению 2:1–4:1
у углов проёма и показывает цену меньшего.
"""
import math

#: Промах оператора в ЭКРАННЫХ пикселях. Допущение до задачи 25 плана 3, где оно
#: измеряется на операторах. Взято 1.64 для любых точек: докстринг
#: `pipeline.run.DEFAULT_MARK_SIGMA_PX` оценивает промах по кромке угла в «~1.5
#: экранных пикселя», обратное разложение `DEFAULT_OPERATOR_SIGMA_PX = 4.5` при
#: уменьшении 2.75× даёт 1.64; различие в пределах точности оценки и о разных
#: задачах не говорит. Берётся бо́льшее — осторожная сторона.
SIGMA_SCREEN_PX = 1.64

#: Размытость кромки в пикселях кадра. Допущение до задачи 25: 1.0 — нижняя граница
#: режима `assisted` п. 6.1, при которой ядро не выполняет субпиксельного уточнения
#: кромки (докстринг `DEFAULT_MARK_SIGMA_PX`). Предполагает РЕЗКУЮ кромку: шлюз по
#: резкости сегодня не отбраковывает ничего (п. 4.1), и связь σ_кромки с резкостью
#: кадра — предмет задачи 25.
SIGMA_EDGE_PX = 1.0

#: Увеличение у углов проёма, ниже которого интерфейс предупреждает оператора. При
#: 2:1 σ = 1.29 px — в пределах трети от предела кромки; дальнейшее увеличение
#: почти ничего не даёт (4:1 — 1.08 px).
RECOMMENDED_MIN_SCALE = 2.0


def sigma_image_px(view_scale: float) -> float:
    """σ клика в пикселях КАДРА при масштабе просмотра `view_scale`.

    Деление, а не умножение: чем крупнее показан кадр, тем меньше пикселей кадра
    стоит один экранный. Перевёрнутая формула давала бы правдоподобные числа и
    ломала бюджет в сторону оптимизма, то есть незаметно; знак проверяется тестом.
    """
    s = float(view_scale)
    if not (math.isfinite(s) and s > 0):
        raise ValueError(f"масштаб просмотра должен быть конечным и положительным: {view_scale!r}")
    return math.hypot(SIGMA_SCREEN_PX / s, SIGMA_EDGE_PX)


def click_sigma(point) -> float:
    """σ точки сессии (`ui.session.ClickedPoint`) — по масштабу, при котором она указана."""
    return sigma_image_px(point.view_scale)


def localisation_cost_mm(view_scale: float, gsd_mm_px: float) -> float:
    """Цена масштаба в мм: слагаемое локализации бюджета п. 6.1, √2·σ·GSD.

    √2 — две независимые кромки, между которыми меряется габарит. Показывается
    оператору рядом с масштабом, чтобы цена грубого просмотра была числом.
    """
    return math.sqrt(2.0) * sigma_image_px(view_scale) * float(gsd_mm_px)
