"""Поле углов визирования по плоскости фасада и локальное разрешение."""
from dataclasses import dataclass
from typing import NamedTuple

import numpy as np

from .camera import CameraOnPlane

#: Сетка узлов КАДРА, на которой считаются поля кадра. Объявлена ЗДЕСЬ и ровно
#: один раз: поле разрешения и поле углов обязаны быть заданы в одних и тех же
#: точках, а посчитанное дважды по двум независимым объявлениям поле молча
#: разошлось бы — доля пригодных узлов считалась бы по одной выборке, а σ
#: элементов по другой. Потребители (`pipeline.run`) импортируют её отсюда, а не
#: объявляют своё значение рядом.
FIELD_SHAPE = (64, 64)


@dataclass(frozen=True)
class AngleMap:
    theta_x: np.ndarray
    theta_y: np.ndarray
    theta_full: np.ndarray
    bounds_mm: tuple


def angle_map(cam: CameraOnPlane, bounds_mm: tuple, shape: tuple) -> AngleMap:
    """Поле углов луча на точки плоскости фасада, в градусах.

    Углы считаются от ОПОРНОЙ ТОЧКИ камеры (cx, cy) — проекции центра камеры на
    плоскость по нормали, — поэтому вычитание опорной точки обязательно: без него
    нуль поля уезжает в начало координат фасада, а это разные точки везде, кроме
    вырожденного случая камеры над углом.

    Компоненты `theta_x` и `theta_y` разведены и знаковые (глобальное ограничение,
    спецификация п. 2.1): `theta_x` растёт вдоль оси X фасада, `theta_y` — вдоль Y.
    Смешивать их между собой и с наклоном камеры `theta_cam` нельзя.
    """
    x0, y0, x1, y1 = bounds_mm
    rows, cols = shape
    gx, gy = np.meshgrid(np.linspace(x0, x1, cols), np.linspace(y0, y1, rows))
    tan_x = (gx - cam.cx) / cam.cz
    tan_y = (gy - cam.cy) / cam.cz
    return AngleMap(np.degrees(np.arctan(tan_x)), np.degrees(np.arctan(tan_y)),
                    np.degrees(np.arctan(np.hypot(tan_x, tan_y))), bounds_mm)


def usable_mask(am: AngleMap, theta_max_deg: float = 30.0) -> np.ndarray:
    """Маска пригодной области: полный угол визирования не превосходит порога."""
    return am.theta_full <= theta_max_deg


class LocalGsdField(NamedTuple):
    """Поле локального разрешения вместе с долей кадра ЗА линией схода.

    Возвращается парой намеренно, по образцу `RecoveredPose`: доля узлов за линией
    схода — не украшение, а условие осмысленности самой величины. Если эта доля
    отлична от нуля, часть кадра не смотрит на плоскость фасада вовсе, и «худшее
    разрешение по кадру» перестаёт быть характеристикой измерения: оно становится
    характеристикой того, насколько близко сетка подошла к линии схода.

    В отличие от позы, здесь есть и вторая, независимая охрана: исключённые узлы
    помечены `nan`, поэтому потребитель, взявший обычный `max()` и не посмотревший
    на долю, получит `nan`, а не правдоподобное число. Оба пути ведут к тому, чтобы
    неисправность сообщила о себе.
    """

    gsd: np.ndarray
    behind_vanishing_line: float


def local_gsd_field(H: np.ndarray, mm_per_rect_unit: float, image_size: tuple,
                    shape: tuple = FIELD_SHAPE,
                    worst_direction: bool = True) -> LocalGsdField:
    """Локальное разрешение по полю кадра вместе с долей узлов за линией схода.

    Миллиметры фасада на один пиксель ИСХОДНОГО снимка. Именно эта величина
    ограничивает точность измерения: ректифицированный растр равномерен по
    построению, неравномерно распределено исходное разрешение.

    Перспектива анизотропна: масштаб вдоль X и вдоль Y в одной точке различается.
    Величина sqrt(|det J|) даёт среднее геометрическое и занижает худший случай на
    единицы процентов. Поскольку требование спецификации (п. 2.2) относится к
    ХУДШЕМУ локальному разрешению, по умолчанию берётся наибольшее сингулярное
    число якобиана.

    **Охрана знака знаменателя.** Знаменатель гомографии `w` обращается в нуль на
    линии схода плоскости фасада и меняет знак за ней. Узлы с иным знаком, чем в
    центре кадра, соответствуют точкам, камерой НЕ видимым: плоскость фасада там
    уже прошла через бесконечность. Такие узлы исключаются (`nan`), а не участвуют
    в максимуме наравне с видимыми. Без этой охраны на почти рёберном ракурсе
    (камера в 200 мм от плоскости, 20 м вбок) половина узлов кадра — мусор, все
    значения конечны, отказа нет, а разброс достигает 1.5e+07 раз: величина, по
    которой спецификация нормирует точность ВСЕХ измерений, считалась бы по
    невидимой части кадра.

    **Величина есть ОЦЕНКА ПО ВЫБОРКЕ, а не точный максимум.** Поле считается в
    узлах регулярной сетки `shape`, и `gsd.max()` — максимум по выборке, снизу
    приближающий истинный. На ракурсах без линии схода внутри кадра это не имеет
    значения: `w` линеен по координатам кадра, поэтому его минимум лежит в углу
    прямоугольника, а углы входят в любую сетку — измерено, что `shape` от 16 до
    2048 даёт совпадающий до последнего знака максимум. Как только линия схода
    входит в кадр, всё меняется: истинная верхняя грань на видимой части кадра
    БЕСКОНЕЧНА (у самой линии схода точка фасада бесконечно далека), сгущение сетки
    максимум не стабилизирует, а безгранично наращивает. Худшее разрешение на таком
    ракурсе надо брать не по всему кадру, а по пригодной области — по маске
    `usable_mask`, которая отсекает окрестность линии схода угловым порогом.
    """
    w_px, h_px = image_size
    rows, cols = shape
    gx, gy = np.meshgrid(np.linspace(0, w_px - 1, cols), np.linspace(0, h_px - 1, rows))

    w = H[2, 0] * gx + H[2, 1] * gy + H[2, 2]
    num_x = H[0, 0] * gx + H[0, 1] * gy + H[0, 2]
    num_y = H[1, 0] * gx + H[1, 1] * gy + H[1, 2]

    # Опорный знак берётся в центре кадра — там же, где его берёт
    # `homography.py` при доопределении ориентации осей; ноль опорного знака
    # означает, что сама линия схода проходит через центр кадра, и делить кадр
    # на видимую и невидимую половины уже не по чему.
    w_ref = H[2, 0] * (w_px / 2.0) + H[2, 1] * (h_px / 2.0) + H[2, 2]
    if not np.isfinite(w_ref) or w_ref == 0.0:
        raise ValueError(
            "знаменатель гомографии в центре кадра вырожден: линия схода проходит "
            "через центр снимка, видимая часть кадра не определена"
        )
    visible = np.sign(w) == np.sign(w_ref)
    behind = float(1.0 - visible.mean())

    with np.errstate(divide="ignore", invalid="ignore"):
        j00 = (H[0, 0] * w - num_x * H[2, 0]) / w ** 2
        j01 = (H[0, 1] * w - num_x * H[2, 1]) / w ** 2
        j10 = (H[1, 0] * w - num_y * H[2, 0]) / w ** 2
        j11 = (H[1, 1] * w - num_y * H[2, 1]) / w ** 2

        det = j00 * j11 - j01 * j10
        if not worst_direction:
            value = mm_per_rect_unit * np.sqrt(np.abs(det))
        else:
            trace = j00 ** 2 + j01 ** 2 + j10 ** 2 + j11 ** 2
            disc = np.clip(trace ** 2 - 4.0 * det ** 2, 0.0, None)
            sigma_max = np.sqrt((trace + np.sqrt(disc)) / 2.0)
            value = mm_per_rect_unit * sigma_max

    return LocalGsdField(np.where(visible, value, np.nan), behind)


def local_gsd(H: np.ndarray, mm_per_rect_unit: float, image_size: tuple,
              shape: tuple = FIELD_SHAPE, worst_direction: bool = True) -> np.ndarray:
    """Одно поле локального разрешения, без доли узлов за линией схода.

    Тонкая обёртка над `local_gsd_field`. Узлы за линией схода помечены `nan`,
    поэтому неисправность не молчит и здесь: `max()` по такому полю даст `nan`.
    Тому, кто принимает решение по доле невидимой части кадра, нужен
    `local_gsd_field`.
    """
    return local_gsd_field(H, mm_per_rect_unit, image_size, shape, worst_direction).gsd
