# Почему двузначность неустранима ЗДЕСЬ и чем она устраняется в интеграции.
# Доказано это для двух точек схода плоскости фасада, а не для постановки вообще:
# (vh, vv) и (-vh, -vv) — одни и те же точки, а два физически допустимых варианта
# осей различаются ровно поворотом на 180°. Признак, разрешающий её, внутри кадра
# существует: линия схода заведомо горизонтальной плоскости (земли), восстановимая
# из тех же отрезков. Это геометрический признак, EXIF для него не нужен.
# Грань откоса для этого непригодна: она указывает на опорную точку, а та уже
# получена из точки схода нормали, то есть независимой опорой не является.
HALF_TURN_UNRESOLVED = (
    "поворот на 180 градусов не определяется двумя точками схода плоскости фасада: "
    "(vh, vv) и (-vh, -vv) задают одни и те же точки"
)
HALF_TURN_RESOLVER = (
    "линия схода заведомо горизонтальной плоскости (земли), восстановимая из тех же "
    "отрезков кадра; разрешение двузначности выносится в интеграцию"
)
HALF_TURN_ASSUMPTION = (
    "снимок считается не перевёрнутым: из двух вариантов взят тот, где ось X фасада "
    "растёт вместе с x изображения"
)


@dataclass(frozen=True)
class HalfTurnAmbiguity:
    """Происхождение выбранной ориентации осей. Спецификация, п. 6.3.

    Величина без указания происхождения в выход не попадает. Поза, которая может
    быть повёрнута на полкруга, обязана нести признак этого, иначе потребитель не
    отличит определённую позу от неопределённой.
    """

    resolved: bool
    assumption: str
    reason: str
    resolver: str


HALF_TURN_FROM_PLANE_VANISHING_POINTS = HalfTurnAmbiguity(
    resolved=False,
    assumption=HALF_TURN_ASSUMPTION,
    reason=HALF_TURN_UNRESOLVED,
    resolver=HALF_TURN_RESOLVER,
)


class RecoveredPose(NamedTuple):
    """Поза вместе с происхождением её ориентации.

    Возвращается парой намеренно: `camera_pose(...).cx` падает с `AttributeError`,
    и потребитель вынужден распаковать пару, то есть увидеть признак. Поле со
    значением по умолчанию этого не дало бы — его можно не читать.

    **Условие, при котором пары станет мало.** Пара — не защита, а напоминание:
    `camera_pose(...)[0]` и `camera, _ = camera_pose(...)` отбрасывают признак
    молча. Сейчас это приемлемо, потому что признак КОНСТАНТЕН: двузначность не
    разрешается никогда, и отбросивший его потребитель ошибается не иногда, а
    всегда — такую ошибку находят сразу. Как только в интеграции появится
    разрешение двузначности по линии схода горизонтальной плоскости, признак
    станет переменным, и отбросивший его получит верный ответ в одних случаях и
    неверный в других. С этого момента пары недостаточно: координаты нельзя будет
    выдавать до того, как двузначность разрешена либо принята явно, то есть
    `camera` должна перестать быть доступной у неразрешённой позы.
    """

    camera: CameraOnPlane
    half_turn: HalfTurnAmbiguity


def _plane_axes(vh, vv, K):
    Kinv = np.linalg.inv(K)
    d1 = Kinv @ np.asarray(vh, dtype=float)
    d1 = d1 / np.linalg.norm(d1)
    d2 = Kinv @ np.asarray(vv, dtype=float)
    d2 = d2 - (d2 @ d1) * d1
    d2 = d2 / np.linalg.norm(d2)
    return d1, d2


# Порог вырожденности признака ориентации. Сравнение относительное: числитель
# производной есть разность двух произведений, и значим не его модуль, а то,
# насколько он уцелел после взаимного вычитания.
_ORIENTATION_MIN_RELATIVE = 1e-12

# Направления кадра, по которым берётся производная: x изображения, затем y.
_IMAGE_X = np.array([1.0, 0.0, 0.0])
_IMAGE_Y = np.array([0.0, 1.0, 0.0])


def _rectified_x_grows_with_image_x(H, image_size):
    """Растёт ли ректифицированная X вместе с x изображения — по производной, точно.

    Признак аналитический, без пробного сдвига. Ректифицированная координата есть
    `x_rect = p0 / p2`, где `p = H · (u, v, 1)`, поэтому

        ∂x_rect/∂u = (dp0 · p2 − p0 · dp2) / p2²,   dp = H · (1, 0, 0).

    Знаменатель `p2²` положителен и на знак не влияет — сравнивается числитель.
    Производная локальна: она берётся в центре кадра и, в отличие от конечной
    разности, не может пересечь линию схода плоскости. Именно этим пробный сдвиг
    и был плох: при камере в 200 мм от плоскости линия схода проходит в 36 px от
    главной точки, сдвиг в 50 px оказывался за ней, знаменатель менял знак, и
    ориентация выбиралась повёрнутой на 180° — при верных углах и верном отношении
    сторон, то есть незаметно.

    **Область применимости правила.** Само правило «X растёт вместе с x изображения»
    опирается на то, что снимок примерно не перевёрнут. Из точек схода определить
    поворот на 180° невозможно в принципе: `(vh, vv)` и `(-vh, -vv)` — одни и те же
    точки, а два оставшихся варианта осей различаются ровно этим поворотом.
    Измерено: правило верно при крене камеры в (−90°, +90°] и даёт повёрнутый на
    180° результат вне этого промежутка. Это свойство постановки, а не реализации.

    **Запасной путь и условие перехода.** При крене ровно ±90° производная по `u`
    обращается в нуль: ось X фасада идёт по вертикали кадра. Условие перехода —
    `|числитель| <= _ORIENTATION_MIN_RELATIVE · |масштаб|`, то есть числитель не
    уцелел после взаимного вычитания. Тогда, и только тогда, знак берётся по
    производной той же ректифицированной X, но по `v`. Конечная разность здесь
    бесполезна: измерено, что при крене 90° она даёт шаг порядка 1e-17, то есть
    чистый шум округления, и вернула бы знак наугад.

    **Асимметрия на ±90° — следствие ЭТОГО выбора, а не постановки.** Крен +90°
    разрешается верно, а −90° нет; крены эти различаются поворотом на 180°, поэтому
    верным может быть ровно один. Какой именно — определяется тем, что при
    вырождении берётся производная по `v` с тем же знаковым правилом («растёт»).
    Взяв противоположное правило, мы получили бы верным −90° и неверным +90°.
    Выбор сделан здесь, сознательно, и никаким свойством задачи не навязан:
    промежуток применимости есть (−90°, +90°], а не [−90°, +90°), именно поэтому.

    Обе производные вырождены быть не могут: это означало бы нулевую строку якобиана
    невырожденной гомографии. Отказ в конце — охрана от порченой `H`, а не рабочий путь.

    Конечность проверяется ДО сравнений: `nan <= 0` и `abs(nan) > x` ложны, и
    обе охраны пропустили бы `nan` насквозь. Путь этот не умозрительный: нулевая
    точка схода даёт nan по всей матрице.
    """
    w, h = image_size
    p = H @ np.array([w / 2.0, h / 2.0, 1.0])
    if not np.all(np.isfinite(p)):
        raise ValueError(
            "образ центра кадра неконечен: точки схода вырождены"
        )
    if p[2] <= 0:
        raise ValueError(
            "центр кадра не лежит перед плоскостью фасада: ориентация осей не определена"
        )

    for direction in (_IMAGE_X, _IMAGE_Y):
        dp = H @ direction
        numerator = dp[0] * p[2] - p[0] * dp[2]
        magnitude = abs(dp[0] * p[2]) + abs(p[0] * dp[2])
        if not (np.isfinite(numerator) and np.isfinite(magnitude)):
            continue
        if magnitude <= 0:
            continue
        if abs(numerator) <= _ORIENTATION_MIN_RELATIVE * magnitude:
            continue  # производная утонула во взаимном вычитании
        return bool(numerator > 0)

    raise ValueError(
        "градиент ректифицированной X в центре кадра вырожден: "
        "ориентация осей не определена"
    )


def homography_from_vanishing_points(vh, vv, K, image_size):
    """Изображение -> фронто-параллельный вид, с однозначно заданной ориентацией осей.

    Знак точки схода произволен (v и -v — одна точка), поэтому осям нужно
    доопределение. Существенно, что оси связаны: третья строка гомографии есть
    d1 x d2, поэтому смена знака d1 переворачивает не X, а Y. Физически допустимы
    лишь две комбинации — (d1, d2) и (-d1, -d2), различающиеся поворотом на 180°;
    остальные дают зеркальное отражение, которого при взгляде спереди быть не может.

    Порядок: сначала фиксируется знак нормали (знаменатель гомографии положителен
    для видимых точек), затем из двух оставшихся вариантов выбирается тот, где ось X
    растёт вместе с x изображения. Второй шаг вынесен в `_rectified_x_grows_with_image_x`:
    он обязан отвергнуть вырожденную пробу, а не выбрать знак наугад.

    Следствие устройства: результат не зависит от знаков `vh` и `vv`. Все четыре
    сочетания знаков сходятся к одной и той же паре осей — первый шаг приводит к
    одному знаку нормали, второй разбирает оставшийся поворот на 180 градусов.
    """
    d1, d2 = _plane_axes(vh, vv, K)
    Kinv = np.linalg.inv(K)
    w, h = image_size

    centre_ray = Kinv @ np.array([w / 2.0, h / 2.0, 1.0])
    if np.cross(d1, d2) @ centre_ray < 0:
        d1 = -d1  # переворачивает нормаль, сохраняя правую тройку

    def build(a1, a2):
        return np.column_stack([a1, a2, np.cross(a1, a2)]).T @ Kinv

    H = build(d1, d2)
    if not _rectified_x_grows_with_image_x(H, image_size):
        H = build(-d1, -d2)

    return H


def foot_point_in_rectified(H, vh, vv, K):
    """Опорная точка F в ректифицированных координатах.

    Луч из центра камеры вдоль нормали к фасаду пересекает плоскость ровно в F,
    и все точки этого луча имеют один образ — точку схода нормали v3 = K·(d1 x d2).
    Следовательно F = H·v3.
    """
    d1, d2 = _plane_axes(vh, vv, K)
    v3 = K @ np.cross(d1, d2)
    p = H @ v3
    # Прежняя охрана `abs(p[2]) < 1e-12` с сообщением «фасад строго фронтален» была
    # мертва и неверна по существу: для СОГЛАСОВАННОЙ с этими точками схода `H`
    # третья компонента тождественно равна ±1 на любом ракурсе, а фронтальность её
    # не вырождает вовсе. Вырождение наступает по другой причине — когда `H`
    # построена не по этим точкам схода либо сами точки схода вырождены (нулевая
    # точка схода даёт nan по всей матрице). Конечность проверяется ПЕРВОЙ:
    # `abs(nan) < 1e-12` ложно, и прежняя охрана вернула бы (nan, nan) молча.
    if not np.all(np.isfinite(p)) or abs(p[2]) < 1e-12:
        raise ValueError(
            "образ точки схода нормали вырожден: гомография не согласована "
            "с переданными точками схода"
        )
    return (float(p[0] / p[2]), float(p[1] / p[2]))


def apply_homography(H, points):
    """Точки -> их образ под `H`, в неоднородных координатах. Форма выхода — всегда (N, 2).

    Единственная реализация для всех потребителей, применяющих гомографию к
    произвольным точкам (а не к регулярной сетке узлов, как `local_gsd_field`):
    `pipeline/run.py` (сборка конвейера) и `pipeline/elements.py` (оцифровка
    проёмов). Второй, независимой реализации того же деления намеренно нет —
    расхождение между копиями было бы невидимо потребителю.

    Деление на ноль подавлено осознанно: знаменатель гомографии обнуляется на
    линии схода, и вызывающий код обязан заметить это по неконечному результату
    точки, а не по брошенному предупреждению numpy.
    """
    pts = np.atleast_2d(np.asarray(points, dtype=float))
    homogeneous = np.column_stack([pts, np.ones(len(pts))]) @ np.asarray(H, dtype=float).T
    with np.errstate(divide="ignore", invalid="ignore"):
        return homogeneous[:, :2] / homogeneous[:, 2:3]


def rectified_to_facade_mm(points_rect, origin_rect, mm_per_rect_unit):
    """Ректифицированные координаты -> миллиметры в системе фасада.

    Ректифицированный растр — изображение, его ось Y направлена вниз; ось Y фасада
    направлена вверх (глобальное ограничение). Переворот выполняется здесь, в одном
    месте, а не внутри гомографии: гомография остаётся ориентацию сохраняющей, иначе
    получилось бы зеркальное отражение фасада.
    """
    ox, oy = origin_rect
    p = np.atleast_2d(np.asarray(points_rect, dtype=float))
    return np.column_stack([(p[:, 0] - ox) * mm_per_rect_unit,
                            -(p[:, 1] - oy) * mm_per_rect_unit])


POSE_NEEDS_VANISHING_POINTS = (
    "поза не восстановима без точек схода и калибровки: опорная точка есть образ "
    "точки схода нормали, и взять её больше неоткуда"
)
POSE_RECT_UNIT_NOT_DISTANCE = (
    "ректифицированная единица не равна расстоянию до плоскости: гомография "
    "построена не по этим точкам схода с этой калибровкой"
)

# Допуск ортонормальности строк `H·K`. Величина не «с запасом»: для гомографии из
# точек схода `H·K` есть матрица из трёх орторномированных направлений, и уцелевшая
# после `K⁻¹K` погрешность составляет порядка 1e-13 при числе обусловленности K
# около 4.5e3. Допуск в 1e-6 на семь порядков шире этой погрешности и на много
# порядков уже любого настоящего рассогласования масштаба: ручной путь по четырём
# точкам даёт строки нормы 8e-5 (размеры в миллиметрах) или 0.6 (отношение сторон).
_RECT_UNIT_ATOL = 1e-6


def camera_pose(H, vh, vv, K, mm_per_rect_unit, origin_rect):
    """Поза камеры относительно плоскости фасада в миллиметрах, с происхождением.

    Опорная точка ВЫЧИСЛЯЕТСЯ, а не постулируется: она есть `foot_point_in_rectified`,
    то есть образ точки схода нормали. Прежняя редакция брала вместо неё начало
    ректифицированных координат. Для гомографии из точек схода это верно тождественно
    (`H·v3 = (0, 0)`), но ровно поэтому было и незаметно, что `H`, `vh`, `vv` и `K` в
    тело не входят вовсе: вызов с вырожденными значениями всех четырёх давал тот же
    ответ, что и вызов с настоящими.

    **Почему одного вычисления опорной точки мало.** Равенство «одна ректифицированная
    единица = расстояние до плоскости» — свойство ТОЙ ЖЕ конструкции, а не любой
    гомографии. Ручной путь п. 4.2 (`homography_from_four_points` с `aspect_ratio`
    либо `size_mm`) ставит и начало, и масштаб ректифицированной системы произвольно:
    опорная точка после починки получалась бы верной, а `cz` оставалось бы неверным
    в отношении этого произвольного масштаба — то есть молча выдуманным. Поэтому
    согласованность проверяется прямо: строки `H·K` обязаны быть ортонормальны, как у
    матрицы `[d1, d2, d1 x d2]`. Ручной путь без калибровки этого не выполняет и
    получает ОТКАЗ с названной причиной, а не правдоподобное число. Ручной путь с
    `assume_calibrated=True` строит ту же самую гомографию из точек схода и проходит.

    Отсутствующие `vh`, `vv` или `K` (их и возвращает `estimate_plane_manual`)
    отвергаются раньше и отдельной причиной: это не рассогласование, а нехватка
    входа, и путать их в сообщении нельзя.

    Возвращается ПАРА `(camera, half_turn)`, а не одна поза. Причина — глобальное
    ограничение: величина без указания происхождения в выход не попадает. Опорная
    точка получена при недоказуемом здесь предположении, что снимок не перевёрнут;
    если оно неверно, обе её координаты меняют знак, а расстояние остаётся верным.
    Потребитель обязан это увидеть, поэтому признак не сделан полем со значением по
    умолчанию: `camera_pose(...).cx` падает, распаковка пары — нет.

    Само расстояние `cz` двузначностью не затронуто.
    """
    if vh is None or vv is None or K is None:
        raise ValueError(POSE_NEEDS_VANISHING_POINTS)

    M = np.asarray(H, dtype=float) @ np.asarray(K, dtype=float)
    # Конечность проверяется ДО сравнения: `np.allclose` на nan возвращает False и
    # увела бы отказ в верную ветку по случайной причине, а не по своей.
    if not np.all(np.isfinite(M)) or not np.allclose(M @ M.T, np.eye(3),
                                                     atol=_RECT_UNIT_ATOL, rtol=0.0):
        raise ValueError(POSE_RECT_UNIT_NOT_DISTANCE)

    foot_rect = foot_point_in_rectified(H, vh, vv, K)
    foot_mm = rectified_to_facade_mm([foot_rect], origin_rect, mm_per_rect_unit)[0]
    camera = CameraOnPlane(cx=float(foot_mm[0]), cy=float(foot_mm[1]),
                           cz=float(mm_per_rect_unit))
    return RecoveredPose(camera=camera,
                         half_turn=HALF_TURN_FROM_PLANE_VANISHING_POINTS)


def homography_from_four_points(image_pts, aspect_ratio=None, size_mm=None,
                                assume_calibrated=False, K=None, image_size=None):
    """Ручной вариант: четыре точки плюс одно из трёх доопределений."""
    import cv2

    given = sum(x is not None for x in (aspect_ratio, size_mm)) + int(assume_calibrated)
    if given == 0:
        raise ValueError(
            "четырёх точек недостаточно: задайте aspect_ratio, size_mm либо "
            "assume_calibrated=True вместе с K"
        )
    if given > 1:
        # `given` иначе использовалась бы только по знаку: при двух доопределениях
        # сразу одно из них молча отбрасывалось бы (ветка ниже берёт size_mm и не
        # смотрит на aspect_ratio). Противоречивый вход отвергается, а не толкуется.
        raise ValueError(
            "доопределение должно быть ровно одно: aspect_ratio, size_mm либо "
            "assume_calibrated, но не несколько сразу"
        )
    if assume_calibrated:
        if K is None or image_size is None:
            raise ValueError("для assume_calibrated нужны K и image_size")
        vh, vv = quad_vanishing_points(image_pts)
        return homography_from_vanishing_points(vh, vv, K, image_size)

    w, h = size_mm if size_mm is not None else (float(aspect_ratio), 1.0)
    src = np.asarray(image_pts, dtype=np.float32)
    dst = np.array([[0.0, 0.0], [w, 0.0], [w, h], [0.0, h]], dtype=np.float32)
    return cv2.getPerspectiveTransform(src, dst).astype(float)



def quad_vanishing_points(image_pts):
    """Точки схода противоположных сторон четырёхугольника (однородные).

    Порядок углов — оператора: верхний левый, верхний правый, нижний правый, нижний
    левый. `vh` — пересечение верхней и нижней сторон, `vv` — левой и правой.
    """
    src = np.asarray(image_pts, dtype=float)
    l_top = np.cross(np.append(src[0], 1.0), np.append(src[1], 1.0))
    l_bot = np.cross(np.append(src[3], 1.0), np.append(src[2], 1.0))
    l_lft = np.cross(np.append(src[0], 1.0), np.append(src[3], 1.0))
    l_rgt = np.cross(np.append(src[1], 1.0), np.append(src[2], 1.0))
    return np.cross(l_top, l_bot), np.cross(l_lft, l_rgt)


#: Ориентация осей, заданная оператором порядком углов. План 3, задача 5.
#:
#: Гомография по четырём точкам и известной форме прямоугольника отображает
#: первую указанную точку в начало, а обход — в заданном порядке: оператор тем
#: самым назвал, где у фасада верх. Двузначность поворота на полкруга, которую
#: две точки схода разрешить не могут (`HALF_TURN_FROM_PLANE_VANISHING_POINTS`),
#: здесь снята — ровно в той мере, в какой оператор не перепутал порядок.
HALF_TURN_FROM_OPERATOR_ORDER = HalfTurnAmbiguity(
    resolved=True,
    assumption="верх фасада — там, где его указал оператор порядком углов: "
               "верхний левый, верхний правый, нижний правый, нижний левый",
    reason="ориентацию осей задал оператор; точки схода для этого не требовались",
    resolver="порядок углов, указанный оператором",
)


def pose_from_homography(H, K, mm_per_rect_unit, origin_rect,
                         half_turn: HalfTurnAmbiguity = HALF_TURN_FROM_PLANE_VANISHING_POINTS
                         ) -> RecoveredPose:
    """Поза камеры разложением гомографии при известной K. План 3, задача 5.

    Обобщение `camera_pose`: та требует гомографии в соглашении «ректифицированная
    единица равна расстоянию до плоскости» и точек схода, а ручная плоскость по
    отношению сторон или двум размерам (п. 4.2) даёт гомографию в единицах самого
    прямоугольника и точек схода не даёт. Разложение работает для любой
    невырожденной H:

        K⁻¹ H⁻¹ = λ [r1 r2 t],

    где r1, r2 — оси плоскости в системе камеры, t — начало ректифицированных
    координат. Знак λ выбирается так, чтобы плоскость лежала перед камерой (t_z > 0);
    столбцы [r1 r2 r1×r2] приводятся к ближайшему повороту (SVD): при неточной K
    они не ортонормированы, и это отклонение меряет `homography_axes_consistency`.
    Центр камеры в системе плоскости — C = −Rᵀt; опорная точка — (C_u, C_v),
    расстояние — |C_w|, оба в ректифицированных единицах, затем в миллиметрах.

    На гомографии из точек схода результат совпадает с `camera_pose` (проверено
    тестом): там H⁻¹ = K [d1 d2 n], λ = 1, и центр камеры лежит на единичном
    расстоянии над началом координат — ровно то, что `camera_pose` утверждает.

    Поза при этом опирается на K. Выпрямление по отношению сторон или двум размерам
    от K не зависит — в этом смысл этих вариантов п. 4.2, — а поза зависит, и K из
    таблицы моделей даёт её с той же ошибкой, что и автоматический путь.
    """
    Hm = np.asarray(H, dtype=float)
    Km = np.asarray(K, dtype=float)
    if not (np.all(np.isfinite(Hm)) and np.all(np.isfinite(Km))):
        raise ValueError("поза не восстановима: гомография или K содержат нечисловые элементы")
    A = np.linalg.inv(Km) @ np.linalg.inv(Hm)
    a1, a2, a3 = A[:, 0], A[:, 1], A[:, 2]
    n1, n2 = float(np.linalg.norm(a1)), float(np.linalg.norm(a2))
    if not (n1 > 0 and n2 > 0):
        raise ValueError("поза не восстановима: гомография вырождена")
    lam = math.sqrt(n1 * n2)
    if a3[2] / lam < 0:
        lam = -lam
    r1, r2, t = a1 / lam, a2 / lam, a3 / lam
    U, _S, Vt = np.linalg.svd(np.column_stack([r1, r2, np.cross(r1, r2)]))
    R = U @ Vt
    if np.linalg.det(R) < 0:
        U[:, -1] = -U[:, -1]
        R = U @ Vt
    C = -R.T @ t
    foot_mm = rectified_to_facade_mm([(float(C[0]), float(C[1]))], origin_rect,
                                     mm_per_rect_unit)[0]
    camera = CameraOnPlane(cx=float(foot_mm[0]), cy=float(foot_mm[1]),
                           cz=float(abs(C[2]) * mm_per_rect_unit))
    return RecoveredPose(camera=camera, half_turn=half_turn)


def homography_axes_consistency(H, K) -> tuple[float, float]:
    """Насколько оси плоскости, вычитанные из H при этой K, ортонормированы.

    Возвращает (угол между осями в градусах, отношение их длин). У верной K и
    верной формы прямоугольника — (90°, 1). Отклонение говорит об ошибке K,
    неверно заданном отношении сторон или промахе указания углов, но не о том,
    какая из трёх причин действует.
    """
    A = np.linalg.inv(np.asarray(K, dtype=float)) @ np.linalg.inv(np.asarray(H, dtype=float))
    a1, a2 = A[:, 0], A[:, 1]
    cos = float(a1 @ a2 / (np.linalg.norm(a1) * np.linalg.norm(a2)))
    return math.degrees(math.acos(max(-1.0, min(1.0, cos)))), float(
        np.linalg.norm(a1) / np.linalg.norm(a2))
