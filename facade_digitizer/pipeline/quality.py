"""Шлюз пригодности снимка. Отбраковывает, но не улучшает. Спецификация, п. 4.1.

**Что значит «отбраковывает» и где это происходит.** Модуль выносит вердикт; ДЕЙСТВИЕ
по вердикту совершает сборка конвейера, и оно названо по имени:
`pipeline.run.GATE_REJECT_WITHHOLDS_TOLERANCE`. При `reject` у элементов снимка не
выпускается `meets_tolerance` — единственное поле выхода, которое утверждает
соответствие требованиям п. 2.2, — потому что `reject` ставится ровно тогда, когда
кадр требованию п. 2.2 к разрешению не удовлетворяет. Габарит, σ и причины при этом
остаются в файле: шлюз помечает, а не уничтожает улику. Без этой ветви слово «шлюз»
здесь было бы названием без последствий: вердикт считался, записывался и ни на что не
употреблялся.

Генеративное устранение смаза синтезирует границы, которых в кадре не было, а измерение
выполняется именно по границам: снимок стал бы визуально убедительным, а миллиметры —
уверенно неверными. Поэтому модуль только выносит вердикт.

Разделение ответственности. Негодный СНИМОК получает вердикт: это то, ради чего шлюз
существует. Негодный АРГУМЕНТ (нечисловое, бесконечное, отрицательное разрешение, доля
вне [0, 1]) — это поломка вызывающего кода, а не свойство снимка, и он поднимает
ValueError. Вердикт «брак» на такой вход был бы записан в выходной файл как свойство
кадра и стал бы неотличим от честной отбраковки плохого снимка; оператор переснял бы
кадр, а сломанный расчёт остался бы на месте. Спецификация, п. 6.3: значение без
происхождения в выход не попадает — выдуманная причина отбраковки тем более.
"""
import math
from dataclasses import dataclass

import cv2
import numpy as np

from facade_digitizer.geometry.angles import THETA_MAX_DEG
from facade_digitizer.schema import QualityReport

#: Порог углового условия п. 2.2 переэкспортируется отсюда под прежним именем, а
#: объявлен в `geometry.angles`.
#:
#: Это порог ПРИГОДНОСТИ ТОЧКИ, а не порог вердикта, и в `Thresholds` он не входит
#: намеренно. Угловое условие предъявляется элементу, а не кадру (спецификация,
#: п. 4.1); на уровне кадра оно выражается долей пригодной области, и решает в шлюзе
#: именно она — `usable_min_fraction`.
#:
#: Величина живёт в ОДНОМ месте, и это место — `geometry.angles`, где ею же
#: пользуется `usable_mask`. Прежде этот модуль объявлял её числом и утверждал о
#: себе «живёт здесь, а не в двух местах порознь», тогда как `usable_mask`
#: держала рядом собственный литерал `30.0`, то есть второе объявление всё-таки
#: существовало. Обратное направление импорта (геометрия берёт величину у
#: конвейера) недопустимо: `geometry` не зависит от `pipeline` ни в одной точке.
__all__ = [
    "DEFAULT",
    "RESOLUTION_REASON",
    "SHARPNESS_REASON",
    "THETA_MAX_DEG",
    "USABLE_FRACTION_REASON",
    "Thresholds",
    "assess",
    "sharpness",
    "usable_fraction",
]


#: Шаблоны причин отбраковки. Вынесены в имена, а не вписаны в `assess`, по одной
#: причине: текст причины не должен решать вердикт. Прежде `reject` выбирался
#: совпадением по подстроке «разрешение» в уже собранных причинах, то есть
#: вердикт зависел от формулировки — а `pipeline.run._needs_operator_model`
#: складывает для `QualityReport` ТОГО ЖЕ типа причину «разрешение оценено по
#: опорной базе оператора», где то же слово есть, а недостаточного разрешения
#: нет. Теперь условие и признак стоят рядом, а шаблон можно переписать, не
#: тронув вердикта; проверка этой независимости — в
#: `tests/test_quality.py::test_verdict_is_decided_by_the_condition_not_by_the_wording`.
SHARPNESS_REASON = "недостаточная резкость: {value:.2e} < {threshold:.2e}"
RESOLUTION_REASON = "недостаточное разрешение: {value:.1f} мм/px > {threshold}"
USABLE_FRACTION_REASON = "угловому условию удовлетворяет лишь {value:.0%} кадра"


@dataclass(frozen=True)
class Thresholds:
    """Пороги вердикта. Все три подставляемы — калибровка не должна обойти ни один.

    **Порога по P95 углового поля здесь нет, и это решение, а не пропуск.** Угол
    визирования в точке кадра при фронтальном ракурсе равен `arctg(r / f)`, то есть
    определяется ОБЪЕКТИВОМ, а не тем, что и под каким ракурсом снято. Измерено на
    кадре 5280x3956: P95 по кадру равен 38.5° при f = 3600 и 43.6° при f = 3000.
    Порог `P95 <= 30°` выполним, лишь когда диагональное поле зрения не шире 68°, а у
    камеры класса DJI Mavic оно около 84° — такой порог отбраковывал бы ВСЕ снимки
    рабочей аппаратуры, включая идеально фронтальные. Спецификация, п. 4.1.

    Значение sharpness_min ПРЕДВАРИТЕЛЬНОЕ и подлежит замене после калибровки на
    реальных снимках — это отдельная задача этапа 1 спецификации.

    Замеры ниже сделаны на СИНТЕТИЧЕСКОЙ сцене (tests/test_synth.make_scene, кадр
    5280x3956, полутоновый), натурных снимков здесь нет:

        резкая сцена                     2.9e-02
        лёгкое размытие  (9,9), s=3.0    2.7e-04
        сильное размытие (31,31), s=12.0 1.4e-04
        белый шум                        2.0e+01

    Отсюда два следствия, оба против доверия абсолютному порогу.

    Первое: умолчание 1.0e-06 лежит на два порядка НИЖЕ самого размытого из этих
    кадров, то есть по резкости оно сейчас не отбраковывает ничего. Это заведомо
    заниженная граница, а не рабочий порог, и в таком виде она оставлена сознательно:
    занижённый порог пропускает сомнительный кадр дальше по конвейеру, где его ещё
    встретят проверки разрешения и угла, тогда как выдуманный «правдоподобный» порог
    молча отбраковывал бы годные снимки.

    Второе: белый шум набирает по этой метрике почти на три порядка больше, чем резкая
    сцена (20 против 0.029). Шлюз принципиально не отличает детали от шума и должен
    применяться только вместе с проверкой разрешения и доли пригодной области.
    """
    sharpness_min: float = 1.0e-06
    gsd_max_mm_px: float = 5.0
    usable_min_fraction: float = 0.5


DEFAULT = Thresholds()


def _number(name: str, value, low: float, high: float, low_inclusive: bool = True) -> float:
    """Аргумент-число: конечное и в осмысленном диапазоне. Иначе — поломка вызова.

    Проверка типа стоит до isfinite намеренно: math.isfinite(x) на нечисловом значении
    поднимает TypeError, а np.isfinite на строке — тоже TypeError, и без явной проверки
    сообщение было бы про внутренности шлюза, а не про негодный аргумент.
    """
    if value is None or isinstance(value, (str, bytes, bool, complex)):
        raise ValueError(f"{name}: ожидалось вещественное число, получено {value!r}")
    try:
        v = float(value)
    except (TypeError, ValueError):
        raise ValueError(f"{name}: ожидалось вещественное число, получено {value!r}") from None
    if not math.isfinite(v):
        raise ValueError(f"{name}: ожидалось конечное число, получено {v}")
    if v > high or v < low or (v == low and not low_inclusive):
        edge = "(" if not low_inclusive else "["
        raise ValueError(f"{name}: значение {v} вне допустимого {edge}{low}, {high}]")
    return v


def _image(image) -> np.ndarray:
    """Кадр на входе шлюза: двумерный, непустой, из чисел и без нечисловых отсчётов.

    Пустой массив не бывает свойством снимка — это поломка вызывающего кода, и здесь
    действует то же разграничение, что для числовых аргументов. Формально кадр проверяет
    загрузка (задача 10), но шлюз стоит последним рубежом перед измерительным конвейером,
    и полагаться на безошибочность цепочки выше нет оснований.
    """
    # Проверка типа и вида отсчётов слита в одно условие сознательно: np.isfinite на
    # массиве объектов поднимает TypeError, а image.ndim на списке — AttributeError,
    # и отказ был бы про внутренности шлюза вместо негодного аргумента. Принадлежность
    # проверяется по кортежу, а не по строке "uif": пустая строка — её подстрока.
    kind = image.dtype.kind if isinstance(image, np.ndarray) else ""
    if kind not in ("u", "i", "f"):
        raise ValueError(f"изображение: ожидался числовой массив numpy, "
                         f"получено {type(image).__name__}")
    if image.ndim != 2:
        raise ValueError(f"изображение: ожидался двумерный полутоновый кадр, "
                         f"получено измерений: {image.ndim}")
    if image.size == 0:
        raise ValueError("изображение: кадр пуст, измерять нечего")
    if kind == "f" and not bool(np.isfinite(image).all()):
        raise ValueError("изображение: среди отсчётов есть нечисловые или бесконечные")
    return image


def sharpness(image: np.ndarray) -> float:
    """Вариация лапласиана, нормированная на дисперсию яркости.

    Нормировка делает метрику независимой от контраста и экспозиции: иначе тот же самый
    кадр, снятый темнее, получил бы меньшую резкость при неизменной геометрии границ.
    """
    lap = cv2.Laplacian(image, cv2.CV_64F)
    return float(lap.var() / (float(image.std()) ** 2 + 1e-9))


def usable_fraction(theta_field_deg: np.ndarray,
                    theta_max_deg: float | None = None) -> float:
    """Доля кадра, удовлетворяющая угловому условию. Спецификация, п. 4.1.

    Умолчание берётся у `THETA_MAX_DEG` в момент вызова — по той же причине и
    тем же способом, что у `geometry.angles.usable_mask`: иначе «величина живёт
    в одном месте» остаётся утверждением, которого нечем проверить.
    """
    threshold = THETA_MAX_DEG if theta_max_deg is None else theta_max_deg
    return float(np.mean(np.asarray(theta_field_deg) <= threshold))


def assess(image: np.ndarray, gsd_min: float, gsd_max: float, theta_p95: float,
           usable: float = 1.0, thresholds: Thresholds | None = None,
           sharpness_value: float | None = None) -> QualityReport:
    """Вердикт о пригодности снимка. Возвращает QualityReport (схема, раздел 10).

    Поднимает ValueError, если аргументы — числовые или сам кадр — не описывают реальный
    снимок: это поломка вызывающего кода, и маскировать её вердиктом нельзя. Сообщения
    об отказе не пересекаются между собой по подстрокам (см. тесты).

    **`theta_p95` на вердикт не влияет и мёртвым параметром при этом не является.**
    Он проверяется как аргумент и записывается в `QualityReport.theta_field_deg_p95`,
    то есть доходит до выходного файла — справочной величиной, как того требует п. 4.1
    спецификации. Причиной отбраковки он быть не может: угловое условие п. 2.2
    предъявляется ЭЛЕМЕНТУ, а на уровне кадра выражается долей пригодной области
    (`usable`), и решает в шлюзе она. Удалять параметр нельзя — величина перестанет
    попадать в выход; возвращать по нему порог нельзя — он отбраковывает объектив, а
    не снимок (обоснование и замеры в `Thresholds`).
    """
    t = thresholds or DEFAULT

    gsd_min = _number("gsd_min", gsd_min, 0.0, 1.0e6, low_inclusive=False)
    gsd_max = _number("gsd_max", gsd_max, 0.0, 1.0e6, low_inclusive=False)
    theta_p95 = _number("theta_p95", theta_p95, 0.0, 90.0)
    usable = _number("usable", usable, 0.0, 1.0)
    if gsd_min > gsd_max:
        raise ValueError(f"границы разрешения переставлены: {gsd_min} > {gsd_max} мм/px")

    image = _image(image)

    reasons: list[str] = []
    # Резкость от опорной базы не зависит и стоит до 0.7 с на 20 Мп, поэтому
    # фаза кадра (план 3, задача 4) считает её один раз и передаёт сюда.
    sharp = sharpness(image) if sharpness_value is None else float(sharpness_value)
    if not math.isfinite(sharp):
        raise ValueError(f"изображение: резкость неопределена ({sharp})")
    if sharp < t.sharpness_min:
        reasons.append(SHARPNESS_REASON.format(value=sharp, threshold=t.sharpness_min))
    # Признак ставится ТАМ ЖЕ, где проверяется условие, и вердикт решается по
    # нему, а не по поиску подстроки «разрешение» в готовых причинах. Поиск по
    # подстроке ставил вердикт в зависимость от текста сообщений: `run.py`
    # формирует для `QualityReport` того же типа причину «разрешение оценено по
    # опорной базе оператора», в которой то же слово есть, а недостаточного
    # разрешения нет, — и инвариант непересечения подстрок, который проверяет
    # `tests/test_quality.py::test_refusal_messages_do_not_overlap`, к этому
    # набору строк не относится вовсе: он стережёт сообщения ОБ ОТКАЗАХ
    # ValueError, а не причины вердикта.
    resolution_too_coarse = gsd_max > t.gsd_max_mm_px
    if resolution_too_coarse:
        reasons.append(RESOLUTION_REASON.format(value=gsd_max,
                                                threshold=t.gsd_max_mm_px))
    if usable < t.usable_min_fraction:
        reasons.append(USABLE_FRACTION_REASON.format(value=usable))

    if not reasons:
        verdict = "ok"
    elif resolution_too_coarse:
        verdict = "reject"
    else:
        verdict = "degraded"

    return QualityReport(
        verdict=verdict,
        sharpness=sharp,
        gsd_mm_px_min=gsd_min,
        gsd_mm_px_max=gsd_max,
        theta_field_deg_p95=theta_p95,
        reasons=reasons,
    )
